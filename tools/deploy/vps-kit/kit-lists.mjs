#!/usr/bin/env node
// Write the plugin list and the MCP server list for the VPS kit from GI's ~/.claude on the PC. Plugin CACHES are never
// copied: the installer re-installs them with `claude plugin ...` on the VPS.
//
//   node kit-lists.mjs CLAUDE_HOME CLAUDE_JSON SETTINGS.json OUT_PLUGINS_LIST OUT_MCP_TXT
//
// CLAUDE_HOME/plugins/installed_plugins.json and known_marketplaces.json say what is installed and where it came from;
// SETTINGS.json's enabledPlugins says what is switched on (a plugin switched off is listed as skipped). CLAUDE_JSON (the
// PC's ~/.claude.json) is read only for the names, commands and arguments of MCP servers: env values, headers and anything
// else in it are never read into the output. An argument that looks like a credential is replaced by <redacted-arg>.
// plugins.list is tab separated (see install.sh): marketplace NAME REPO | plugin ID VERSION | skip ID REASON.
// Exit codes: 0 written, 1 a file is unreadable or a value is not safe to put on a command line, 2 usage.
import fs from 'node:fs';
import path from 'node:path';

const [claudeHome, claudeJson, settingsFile, outPlugins, outMcp] = process.argv.slice(2);
if (!outMcp) { console.error('usage: kit-lists.mjs CLAUDE_HOME CLAUDE_JSON SETTINGS.json OUT_PLUGINS_LIST OUT_MCP_TXT'); process.exit(2); }

const readJson = (f, what) => {
  try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) {
    console.error(`kit-lists: cannot read ${what} (${e.message.split('\n')[0]})`);
    process.exit(1);
  }
};
const SAFE_ID = /^[A-Za-z0-9._-]+@[A-Za-z0-9._-]+$/;
const SAFE_NAME = /^[A-Za-z0-9._-]+$/;
const SAFE_REPO = /^[A-Za-z0-9._-]+\/[A-Za-z0-9._-]+$/;
const SAFE_VER = /^[A-Za-z0-9._+-]*$/;

const installed = readJson(path.join(claudeHome, 'plugins', 'installed_plugins.json'), 'installed_plugins.json');
const markets = readJson(path.join(claudeHome, 'plugins', 'known_marketplaces.json'), 'known_marketplaces.json');
const settings = readJson(settingsFile, 'settings.json');
const enabled = settings.enabledPlugins || {};

const lines = ['# Generated by tools/deploy/pack-vps-kit.sh from the PC. Tab separated. Read by install.sh.',
  '#   marketplace<TAB>NAME<TAB>OWNER/REPO   -> claude plugin marketplace add OWNER/REPO',
  '#   plugin<TAB>NAME@MARKETPLACE<TAB>VERSION on the PC -> claude plugin install NAME@MARKETPLACE   (the VPS gets the current version)',
  '#   skip<TAB>NAME@MARKETPLACE<TAB>reason'];
const wantedMarkets = new Map();
const pluginLines = [];
for (const [id, entries] of Object.entries(installed.plugins || {})) {
  const entry = Array.isArray(entries) ? entries[0] : entries;
  if (!SAFE_ID.test(id)) { console.error(`kit-lists: plugin id '${id.replace(/[^\x20-\x7e]/g, '?')}' is not a plain NAME@MARKETPLACE`); process.exit(1); }
  const market = id.split('@')[1];
  const version = String(entry?.version ?? '');
  if (!SAFE_VER.test(version)) { console.error(`kit-lists: version of ${id} is not plain text`); process.exit(1); }
  if (enabled[id] === false) { pluginLines.push(`skip\t${id}\tswitched off in settings.json (enabledPlugins false)`); continue; }
  if (!(id in enabled)) { pluginLines.push(`skip\t${id}\tnot listed in enabledPlugins`); continue; }
  const m = markets[market];
  const src = m?.source;
  if (!src || src.source !== 'github' || !SAFE_REPO.test(src.repo ?? '')) {
    pluginLines.push(`skip\t${id}\tmarketplace '${market}' is not a plain GitHub source`);
    continue;
  }
  if (!SAFE_NAME.test(market)) { console.error('kit-lists: marketplace name not plain'); process.exit(1); }
  wantedMarkets.set(market, src.repo);
  pluginLines.push(`plugin\t${id}\t${version}`);
}
for (const [name, repo] of [...wantedMarkets.entries()].sort()) lines.push(`marketplace\t${name}\t${repo}`);
lines.push(...pluginLines);
fs.writeFileSync(outPlugins, lines.join('\n') + '\n', 'utf8');

// ---- MCP servers: names and commands only --------------------------------------------------------------------------------
const cj = readJson(claudeJson, '.claude.json');
const looksSecret = (s) => typeof s === 'string' && (/^(sk-|ghp_|gho_|xox|AIza|eyJ)/.test(s) || (s.length > 28 && /^[A-Za-z0-9_\-+/=]+$/.test(s)));
const describe = (scope, servers) => {
  const out = [];
  for (const [name, c] of Object.entries(servers || {})) {
    const type = c.type || (c.command ? 'stdio' : 'unknown');
    let target = '';
    if (c.command) {
      const a = (Array.isArray(c.args) ? c.args : []).map((x) => (looksSecret(x) ? '<redacted-arg>' : String(x)));
      target = [c.command, ...a].join(' ');
    } else if (c.url) {
      try { const u = new URL(c.url); target = `${u.protocol}//${u.host}${u.pathname}`; } catch { target = '<url>'; }
    }
    const envNames = Object.keys(c.env || {});
    const headerNames = Object.keys(c.headers || {});
    out.push({ scope, name, type, target, envNames, headerNames });
  }
  return out;
};
const all = [...describe('user', cj.mcpServers)];
for (const [proj, v] of Object.entries(cj.projects || {})) all.push(...describe(`project ${proj}`, v?.mcpServers));
const toLinux = (s) => s.replace(/[A-Za-z]:[\\/]+Users[\\/]+[^\\/]+[\\/]+\.claude[\\/]/g, '/root/.claude/').replace(/\\/g, '/');

const m = ['# MCP servers on the PC (from ~/.claude.json): names, commands and arguments only. Env values and headers are never read.',
  '# ~/.claude.json itself is NOT in the kit (it also holds account state), so nothing here is installed by the installer.', ''];
const userServers = all.filter((s) => s.scope === 'user');
m.push(`user-scope servers on the PC: ${userServers.length ? userServers.map((s) => s.name).join(', ') : 'none'}`);
m.push('plugin-provided servers (for example claude-mem mcp-search) come back with their plugin; nothing to add by hand.', '');
for (const s of userServers) {
  m.push(`# ${s.name} (${s.type})`);
  if (s.envNames.length) m.push(`#   needs env: ${s.envNames.join(', ')} (set them by hand on the VPS; the values are not in the kit)`);
  if (s.headerNames.length) m.push(`#   needs headers: ${s.headerNames.join(', ')} (by hand)`);
  m.push(s.type === 'stdio' ? `claude mcp add ${s.name} -s user -- ${toLinux(s.target)}` : `claude mcp add --transport ${s.type} ${s.name} -s user ${s.target}`, '');
}
const projectServers = all.filter((s) => s.scope !== 'user');
if (projectServers.length) {
  m.push('# project-scope servers (set up for other projects on the PC; their folders do not exist on the VPS). Optional, copy a line if you want one:');
  for (const s of projectServers) {
    m.push(`#   ${s.name} (${s.type}) was configured for ${s.scope.replace(/^project /, '')}`);
    if (s.envNames.length) m.push(`#     needs env: ${s.envNames.join(', ')} (by hand)`);
    m.push(`#   claude mcp add ${s.name} -s user -- ${toLinux(s.target)}`);
  }
  m.push('#   (a node server under ~/.claude/tools/<name> needs `npm ci` in that folder first; the kit ships its package.json and lock file only)');
}
fs.writeFileSync(outMcp, m.join('\n') + '\n', 'utf8');
console.log(`[kit-lists] plugins.list: ${wantedMarkets.size} marketplace(s), ${pluginLines.filter((l) => l.startsWith('plugin')).length} plugin(s), ${pluginLines.filter((l) => l.startsWith('skip')).length} skipped; mcp-servers.txt: ${all.length} server(s) described`);
