// Generates the endpoint reference of docs/api.md from the route registry, so the reference can
// never disagree with the code: methods, paths, auth, request fields, rate limits and error codes
// are read from the same definitions the server runs. Examples come from scripts/docs-examples.ts.
//
//   npm run docs:reference            print the reference
//   npm run docs:reference -- --write replace the block between the markers in docs/api.md
//
// check-docs (and test/docs.test.ts) fail when the block in docs/api.md differs from this output.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SQL, getTableName, is } from 'drizzle-orm';
import { PgDialect, PgTable, getTableConfig } from 'drizzle-orm/pg-core';
import type { AnyPgColumn } from 'drizzle-orm/pg-core';
import { z } from 'zod';
import { envSchema } from '../src/config.js';
import * as schema from '../src/db/schema.js';
import { listRoutes } from '../src/http/app.js';
import type { AuthKind, LimitSpec, RouteMeta } from '../src/http/router.js';
import { EXAMPLES, ERROR_CODES } from './docs-examples.js';
import { ENV_NOTES, TABLE_NOTES } from './docs-notes.js';

export const START_MARKER = '<!-- reference:start (generated by npm run docs:reference; do not edit by hand) -->';
export const END_MARKER = '<!-- reference:end -->';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const AUTH_TEXT: Record<AuthKind, string> = {
  none: 'none (public)',
  session: 'session (`Authorization: Bearer <session token>`)',
  mod: 'session of an account with the `mod` or `admin` role',
  admin: 'session of an account with the `admin` role',
  server: 'game server (`X-Gage-Server-Id` + `X-Gage-Server-Secret`, from an allowlisted IP)',
  webhook: 'payment provider signature over the raw body',
};

interface Group {
  title: string;
  match: (r: RouteMeta) => boolean;
}

const GROUPS: Group[] = [
  { title: 'Meta', match: (r) => r.path === '/health' || r.path === '/v1/openapi.json' },
  { title: 'Registration, login and sessions', match: (r) => r.path.startsWith('/v1/auth/') && !r.path.includes('/discord') || r.path === '/v1/me' || r.path === '/v1/me/password' || r.path.startsWith('/v1/me/sessions') },
  { title: 'Discord', match: (r) => r.path.includes('/discord') },
  { title: 'Settings', match: (r) => r.path === '/v1/me/settings' },
  { title: 'Servers and joining', match: (r) => r.path === '/v1/servers' || r.path === '/v1/game/join' },
  { title: 'Shop, orders, wallet and items', match: (r) => r.path.startsWith('/v1/shop/') || r.path.startsWith('/v1/me/wallet') || r.path === '/v1/me/items' },
  { title: 'Quests', match: (r) => r.path.startsWith('/v1/me/quests') },
  { title: 'Payment webhooks and the dev checkout', match: (r) => r.path.startsWith('/v1/webhooks/') || r.path.startsWith('/v1/dev/') },
  { title: 'Moderation and administration', match: (r) => r.path.startsWith('/v1/admin/') },
  { title: 'Game server API (internal listener)', match: (r) => r.path.startsWith('/internal/') },
];

function windowText(seconds: number): string {
  if (seconds % 3600 === 0) return `${seconds / 3600} h`;
  if (seconds % 60 === 0) return `${seconds / 60} min`;
  return `${seconds} s`;
}

function limitText(l: LimitSpec): string {
  return `\`${l.name}\` per ${l.scope === 'ip' ? 'client IP (IPv6: /64)' : 'account'}: ${l.limit} per ${windowText(l.windowSeconds)}`;
}

type Json = Record<string, unknown>;

/** A compact one-line type for a JSON-schema fragment. */
function typeOf(s: Json, depth = 0): string {
  if (Array.isArray(s['enum'])) return (s['enum'] as unknown[]).map((v) => JSON.stringify(v)).join(' \\| ');
  if ('const' in s) return JSON.stringify(s['const']);
  const any = s['anyOf'] ?? s['oneOf'];
  if (Array.isArray(any)) return (any as Json[]).map((x) => typeOf(x, depth)).filter((v, i, a) => a.indexOf(v) === i).join(' \\| ');
  const t = s['type'];
  if (Array.isArray(t)) return t.join(' \\| ');
  if (t === 'array') {
    const items = s['items'] as Json | undefined;
    return `array of ${items ? typeOf(items, depth + 1) : 'any'}`;
  }
  if (t === 'object') {
    const props = s['properties'] as Record<string, Json> | undefined;
    if (!props || depth >= 2) return 'object';
    const required = new Set((s['required'] as string[] | undefined) ?? []);
    return `{ ${Object.entries(props).map(([k, v]) => `${k}${required.has(k) ? '' : '?'}: ${typeOf(v, depth + 1)}`).join(', ')} }`;
  }
  if (typeof t === 'string') return s['format'] ? `${t} (${String(s['format'])})` : t;
  return 'any';
}

function constraintsOf(s: Json): string {
  const out: string[] = [];
  const min = s['minLength'];
  const max = s['maxLength'];
  if (min !== undefined || max !== undefined) out.push(`${min ?? 0}..${max ?? '*'} chars`);
  const lo = s['minimum'];
  const hi = s['maximum'];
  if (lo !== undefined || hi !== undefined) out.push(`${lo ?? '*'}..${hi === 9007199254740991 ? '*' : (hi ?? '*')}`);
  if (typeof s['pattern'] === 'string') out.push(`matches \`${(s['pattern'] as string).replace(/\|/g, '\\|')}\``);
  if (s['minItems'] !== undefined || s['maxItems'] !== undefined) out.push(`${s['minItems'] ?? 0}..${s['maxItems'] ?? '*'} items`);
  if ('default' in s) out.push(`default \`${JSON.stringify(s['default'])}\``);
  if (typeof s['description'] === 'string') out.push(s['description'] as string);
  return out.join('; ');
}

function fieldTable(schema: Json | null, kind: 'body' | 'query'): string[] {
  if (!schema) return [];
  const props = schema['properties'] as Record<string, Json> | undefined;
  if (!props || Object.keys(props).length === 0) {
    return [`**${kind === 'body' ? 'Request body' : 'Query string'}**`, '', kind === 'body' ? 'A JSON object (see the description above).' : 'none', ''];
  }
  const required = new Set((schema['required'] as string[] | undefined) ?? []);
  const lines = [`**${kind === 'body' ? 'Request body (JSON)' : 'Query string'}**`, '', '| field | type | required | rules |', '| --- | --- | --- | --- |'];
  for (const [name, s] of Object.entries(props)) {
    lines.push(`| \`${name}\` | ${typeOf(s)} | ${required.has(name) ? 'yes' : 'no'} | ${constraintsOf(s) || ''} |`);
  }
  lines.push('');
  return lines;
}

function pathParams(r: RouteMeta): string[] {
  const names = [...r.path.matchAll(/:([A-Za-z0-9_]+)/g)].map((m) => m[1] as string);
  if (names.length === 0) return [];
  const lines = ['**Path parameters**', ''];
  for (const n of names) {
    const what =
      r.path.includes('/servers/') ? 'server id (`^[a-z0-9][a-z0-9-]{1,31}$`)'
      : n === 'provider' ? 'payment provider id (for example `fake`)'
      : 'UUID';
    lines.push(`- \`${n}\`: ${what}`);
  }
  lines.push('');
  return lines;
}

function exampleBlock(r: RouteMeta, key: string): string[] {
  const ex = EXAMPLES[key];
  if (!ex) return [`**Example**`, '', '_missing_', ''];
  const req: string[] = [`${r.method.toUpperCase()} ${ex.path ?? r.path}`];
  if (r.auth === 'session' || r.auth === 'mod' || r.auth === 'admin') req.push('Authorization: Bearer <session token>');
  if (r.auth === 'server') req.push('X-Gage-Server-Id: eu-1', 'X-Gage-Server-Secret: <server secret>');
  for (const [k, v] of Object.entries(ex.headers ?? {})) req.push(`${k}: ${v}`);
  if (ex.request !== undefined) req.push('Content-Type: application/json', '', typeof ex.request === 'string' ? ex.request : JSON.stringify(ex.request, null, 2));
  const status = ex.status ?? r.successStatus;
  const res: string[] = [`HTTP ${status}`];
  if (ex.response !== undefined) res.push('', typeof ex.response === 'string' ? ex.response : JSON.stringify(ex.response, null, 2));
  return ['**Example**', '', '```http', ...req, '```', '', '```http', ...res, '```', '', ...(ex.note ? [ex.note, ''] : [])];
}

function renderRoute(r: RouteMeta, schemas: { body: Json | null; query: Json | null }): string[] {
  const key = `${r.method.toUpperCase()} ${r.path}`;
  const lines = [`### ${key}`, '', r.summary + (r.summary.endsWith('.') ? '' : '.'), ''];
  if (r.description) lines.push(r.description, '');
  lines.push(`- **Auth:** ${AUTH_TEXT[r.auth]}`);
  lines.push(`- **Listener:** ${r.surface === 'both' ? 'public and internal' : r.surface}`);
  lines.push(`- **Rate limits:** ${r.limits.length === 0 ? 'none beyond the global body limit' : r.limits.map(limitText).join('; ')}`);
  lines.push(`- **Success:** HTTP ${r.successStatus}, ${r.response.replace(/^\d{3}\s*/, '')}`);
  if (r.maxBodyBytes !== undefined) lines.push(`- **Body limit:** ${r.maxBodyBytes} bytes`);
  const codes = r.errors;
  lines.push(`- **Errors:** ${codes.length === 0 ? 'only the generic ones' : codes.map((c) => `\`${c}\``).join(', ')}`);
  lines.push('');
  lines.push(...pathParams(r));
  lines.push(...fieldTable(schemas.body, 'body'));
  lines.push(...fieldTable(schemas.query, 'query'));
  lines.push(...exampleBlock(r, key));
  return lines;
}

const toSchema = (s: z.ZodType | undefined): Json | null => (s ? (z.toJSONSchema(s, { io: 'input', unrepresentable: 'any' }) as Json) : null);

/** The generated reference text (without the markers). */
export function renderReference(): string {
  const routes = listRoutes();
  const used = new Set<RouteMeta>();
  const out: string[] = [];
  for (const g of GROUPS) {
    const members = routes.filter((r) => g.match(r) && !used.has(r));
    if (members.length === 0) continue;
    out.push(`## ${g.title}`, '');
    for (const r of members) {
      used.add(r);
      out.push(...renderRoute(r, { body: toSchema(r.body), query: toSchema(r.query) }));
    }
  }
  const leftover = routes.filter((r) => !used.has(r));
  if (leftover.length > 0) throw new Error(`routes without a documentation group: ${leftover.map((r) => `${r.method} ${r.path}`).join(', ')}`);
  out.push(...renderErrors(routes), ...renderTables(), ...renderEnv());
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

const dialect = new PgDialect();
/** SQL fragment as text, with `"table"."column"` shortened to `column`. */
const sqlText = (value: unknown): string =>
  dialect
    .sqlToQuery(value as Parameters<PgDialect['sqlToQuery']>[0])
    .sql.replace(/"[a-z_]+"\."([a-z_]+)"/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
const cell = (s: string): string => s.replace(/\|/g, '\\|');

function renderErrors(routes: RouteMeta[]): string[] {
  const lines = ['## Error codes', '', '| code | meaning | returned by |', '| --- | --- | --- |'];
  const byCode = new Map<string, string[]>();
  for (const r of routes) for (const c of r.errors) byCode.set(c, [...(byCode.get(c) ?? []), `${r.method.toUpperCase()} ${r.path}`]);
  for (const code of Object.keys(ERROR_CODES).sort()) {
    const where = byCode.get(code) ?? [];
    lines.push(`| \`${code}\` | ${cell(ERROR_CODES[code] as string)} | ${where.length === 0 ? 'any route (generic)' : where.map((w) => `\`${w}\``).join('<br>')} |`);
  }
  lines.push('');
  return lines;
}

function defaultText(c: AnyPgColumn): string | null {
  if (c.generatedIdentity) return 'identity';
  if (!c.hasDefault) return null;
  const d: unknown = c.default;
  if (typeof d === 'string' || typeof d === 'number' || typeof d === 'boolean') return `default \`${JSON.stringify(d)}\``;
  if (is(d, SQL)) return `default \`${sqlText(d)}\``;
  if (d !== undefined && d !== null) return `default \`${JSON.stringify(d)}\``;
  return 'default generated';
}

function renderTables(): string[] {
  const lines = ['## Tables', '', 'Columns, indexes and checks are read from `src/db/schema.ts`; triggers are in `drizzle/0001_invariants.sql`. All timestamps are `timestamptz`.', ''];
  const tables = Object.values(schema as Record<string, unknown>).filter((v): v is PgTable => is(v, PgTable));
  for (const t of tables.sort((a, b) => getTableName(a).localeCompare(getTableName(b)))) {
    const name = getTableName(t);
    const note = TABLE_NOTES[name];
    const cfg = getTableConfig(t);
    lines.push(`#### \`${name}\``, '', note ? note.purpose : '_no note_', '');
    lines.push('| column | type | null | notes |', '| --- | --- | --- | --- |');
    for (const c of cfg.columns as AnyPgColumn[]) {
      const notes = [c.primary ? 'primary key' : null, defaultText(c)].filter((x): x is string => x !== null);
      lines.push(`| \`${c.name}\` | ${c.getSQLType()} | ${c.notNull ? 'no' : 'yes'} | ${cell(notes.join('; '))} |`);
    }
    lines.push('');
    const rules: string[] = [];
    for (const pk of cfg.primaryKeys) rules.push(`primary key (${pk.columns.map((c) => c.name).join(', ')})`);
    for (const u of cfg.uniqueConstraints) rules.push(`unique \`${u.name}\` (${u.columns.map((c) => c.name).join(', ')})`);
    for (const i of cfg.indexes) {
      const cols = (i.config.columns as unknown[]).map((c) => (typeof c === 'object' && c !== null && 'name' in c ? String((c as { name: string }).name) : sqlText(c))).join(', ');
      rules.push(`${i.config.unique ? 'unique index' : 'index'} \`${i.config.name}\` (${cols})${i.config.where ? ` where ${sqlText(i.config.where)}` : ''}`);
    }
    for (const f of cfg.foreignKeys) {
      const ref = f.reference();
      rules.push(`foreign key \`${f.getName()}\` (${ref.columns.map((c) => c.name).join(', ')}) references ${getTableName(ref.foreignTable)} (${ref.foreignColumns.map((c) => c.name).join(', ')}) on delete ${f.onDelete ?? 'no action'}`);
    }
    for (const c of cfg.checks) rules.push(`check \`${c.name}\`: ${sqlText(c.value)}`);
    if (rules.length > 0) lines.push('Constraints and indexes', '', ...rules.map((r) => `- ${cell(r)}`), '');
    if (note) lines.push('Invariants', '', ...note.invariants.map((i) => `- ${i}`), '');
  }
  return lines;
}

function renderEnv(): string[] {
  const defaults = envSchema.parse({}) as Record<string, unknown>;
  const lines = [
    '## Environment variables',
    '',
    'Unset and empty variables take the default. Integers are plain base-10 digits; flags are exactly `0` or `1`. A bad value stops the process at start with every problem listed (secrets are never echoed).',
    '',
    '| variable | default | meaning |',
    '| --- | --- | --- |',
  ];
  for (const name of Object.keys(envSchema.shape)) {
    const d = defaults[name];
    const shown = d === undefined ? '_unset_' : `\`${typeof d === 'boolean' ? (d ? '1' : '0') : String(d)}\``;
    lines.push(`| \`${name}\` | ${shown} | ${cell(ENV_NOTES[name] ?? '_no note_')} |`);
  }
  lines.push('');
  return lines;
}

/** Routes without an example, and error codes used by a route but missing from ERROR_CODES. */
export function referenceProblems(): string[] {
  const problems: string[] = [];
  for (const r of listRoutes()) {
    const key = `${r.method.toUpperCase()} ${r.path}`;
    if (!EXAMPLES[key]) problems.push(`docs-examples.ts has no example for "${key}"`);
    for (const c of r.errors) if (!ERROR_CODES[c]) problems.push(`docs-examples.ts does not explain the error code "${c}" (used by ${key})`);
  }
  for (const name of Object.keys(envSchema.shape)) if (!ENV_NOTES[name]) problems.push(`docs-notes.ts has no note for the environment variable ${name}`);
  for (const name of Object.keys(ENV_NOTES)) if (!(name in envSchema.shape)) problems.push(`docs-notes.ts describes an environment variable that does not exist: ${name}`);
  const tableNames = Object.values(schema as Record<string, unknown>).filter((v): v is PgTable => is(v, PgTable)).map((t) => getTableName(t));
  for (const name of tableNames) if (!TABLE_NOTES[name]) problems.push(`docs-notes.ts has no note for the table ${name}`);
  for (const name of Object.keys(TABLE_NOTES)) if (!tableNames.includes(name)) problems.push(`docs-notes.ts describes a table that does not exist: ${name}`);
  const known = new Set(listRoutes().map((r) => `${r.method.toUpperCase()} ${r.path}`));
  for (const key of Object.keys(EXAMPLES)) if (!known.has(key)) problems.push(`docs-examples.ts has an example for a route that does not exist: "${key}"`);
  return problems;
}

/** The block currently stored in docs/api.md, or null when the markers are missing. */
export function storedReference(api: string): string | null {
  const a = api.indexOf(START_MARKER);
  const b = api.indexOf(END_MARKER);
  if (a < 0 || b < a) return null;
  return api.slice(a + START_MARKER.length, b).replace(/^\n+/, '');
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const problems = referenceProblems();
  for (const p of problems) process.stderr.write(`${p}\n`);
  if (problems.length > 0) process.exit(1);
  const text = renderReference();
  if (process.argv.includes('--write')) {
    const file = join(root, 'docs', 'api.md');
    const api = readFileSync(file, 'utf8');
    const a = api.indexOf(START_MARKER);
    const b = api.indexOf(END_MARKER);
    if (a < 0 || b < a) {
      process.stderr.write('docs/api.md has no reference markers\n');
      process.exit(1);
    }
    writeFileSync(file, `${api.slice(0, a + START_MARKER.length)}\n\n${text}\n${api.slice(b)}`, 'utf8');
    process.stdout.write('docs/api.md reference updated\n');
  } else {
    process.stdout.write(text);
  }
}
